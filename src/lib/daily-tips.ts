/** انتخاب یکتا بر اساس تاریخ روز + نام کاربری (تکرار در همان روز برای همان کاربر رخ نمی‌دهد). */
export function pickDailyTip(username: string, date = new Date()): { index: number; text: string } {
  const dayKey = `${date.getFullYear()}-${date.getMonth() + 1}-${date.getDate()}`;
  const seed = `${dayKey}|${username.trim().toLowerCase()}`;
  let hash = 0;
  for (let i = 0; i < seed.length; i++) {
    hash = (hash * 31 + seed.charCodeAt(i)) >>> 0;
  }
  const index = hash % DAILY_TIPS.length;
  return { index, text: DAILY_TIPS[index]! };
}

const STORAGE_KEY = "sibamotor-daily-tip-seen";

export function hasSeenTipToday(username: string): boolean {
  if (typeof window === "undefined") return true;
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return false;
    const data = JSON.parse(raw) as { day: string; user: string };
    const today = new Date();
    const dayKey = `${today.getFullYear()}-${today.getMonth() + 1}-${today.getDate()}`;
    return data.day === dayKey && data.user === username.trim().toLowerCase();
  } catch {
    return false;
  }
}

export function markTipSeenToday(username: string): void {
  if (typeof window === "undefined") return;
  const today = new Date();
  const dayKey = `${today.getFullYear()}-${today.getMonth() + 1}-${today.getDate()}`;
  localStorage.setItem(
    STORAGE_KEY,
    JSON.stringify({ day: dayKey, user: username.trim().toLowerCase() }),
  );
}
