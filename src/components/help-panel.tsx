export function HelpButton({
  className,
  onStartTour,
}: {
  className?: string;
  onStartTour?: () => void;
}) {
  const [open, setOpen] = useState(false);
  const [tab, setTab] = useState(SECTIONS[0]!.id);
  const [q, setQ] = useState("");

  const results = useMemo(() => {
    const s = q.trim().toLowerCase();
    if (!s) return null;
    return SECTIONS.map((sec) => ({
      sec,
      blocks: sec.blocks.filter((b) =>
        [b.h, b.p, b.tip, ...(b.items ?? []), ...(b.steps ?? [])]
          .filter(Boolean)
          .join(" ")
          .toLowerCase()
          .includes(s),
      ),
    })).filter((r) => r.blocks.length > 0);
  }, [q]);

  const current = SECTIONS.find((s) => s.id === tab) ?? SECTIONS[0]!;
  const view = results ?? [{ sec: current, blocks: current.blocks }];

  return (
    <>
      <Button
        variant="ghost"
        size="icon-sm"
        className={cn(className)}
        aria-label="راهنما"
        title="دفترچه راهنمای سامانه"
        onClick={() => setOpen(true)}
      >
        <BookOpen className="size-4" />
      </Button>
      <Dialog open={open} onOpenChange={setOpen}>
        <DialogContent className="flex h-[min(85vh,680px)] max-w-3xl flex-col gap-0 overflow-hidden p-0">
          <div className="border-b border-border px-5 pb-3 pt-4">
            <DialogTitle className="text-base font-semibold">
              راهنمای سیباموتور
            </DialogTitle>
            <DialogDescription className="mt-0.5 text-[12px]">
              همه‌چیز برای شروع، حتی اگر قبلاً با کانبان و اسکرام کار نکرده‌اید.
            </DialogDescription>
            <div className="mt-3 flex flex-wrap items-center gap-2">
              <div className="flex h-9 min-w-[10rem] flex-1 items-center gap-2 rounded-full border border-border bg-surface-2 px-3">
                <Search className="size-4 shrink-0 text-subtle" />
                <input
                  value={q}
                  onChange={(e) => setQ(e.target.value)}
                  placeholder="جستجو در راهنما… مثلاً امتیاز، گزارش، مانع"
                  className="w-full bg-transparent text-[13px] outline-none"
                />
              </div>
              {onStartTour && (
                <Button
                  size="sm"
                  variant="secondary"
                  onClick={() => {
                    setOpen(false);
                    onStartTour();
                  }}
                >
                  <GraduationCap className="size-4" />
                  آموزش مرحله‌به‌مرحله
                </Button>
              )}
            </div>
          </div>
          <div className="flex min-h-0 flex-1 flex-col sm:flex-row">
            <nav className="k-scroll flex shrink-0 gap-1 overflow-x-auto border-b border-border p-2 sm:w-48 sm:flex-col sm:overflow-y-auto sm:border-b-0 sm:border-e">
              {SECTIONS.map((s) => (
                <button
                  key={s.id}
                  type="button"
                  onClick={() => {
                    setTab(s.id);
                    setQ("");
                  }}
                  className={cn(
                    "flex shrink-0 items-center gap-2 rounded-lg px-3 py-2 text-start text-[13px]",
                    !results && tab === s.id
                      ? "bg-accent text-accent-fg"
                      : "text-muted hover:bg-accent-soft hover:text-fg",
                  )}
                >
                  <span aria-hidden>{s.emoji}</span>
                  <span className="whitespace-nowrap">{s.title}</span>
                </button>
              ))}
            </nav>
            <div className="k-scroll min-h-0 flex-1 overflow-y-auto px-5 py-4">
              {results && results.length === 0 && (
                <p className="py-10 text-center text-sm text-muted">
                  چیزی پیدا نشد.
                </p>
              )}
              {view.map(({ sec, blocks }) => (
                <section key={sec.id} className="mb-6 last:mb-0">
                  <h2 className="mb-3 flex items-center gap-2 text-[15px] font-semibold">
                    <span aria-hidden>{sec.emoji}</span>
                    {sec.title}
                  </h2>
                  <div className="space-y-4">
                    {blocks.map((b, i) => (
                      <div key={i} className="space-y-2">
                        {b.h && (
                          <h3 className="text-[13px] font-semibold">{b.h}</h3>
                        )}
                        {b.p && (
                          <p className="text-[13px] leading-7 text-muted">
                            {b.p}
                          </p>
                        )}
                        {b.steps && (
                          <ol className="space-y-2">
                            {b.steps.map((t, n) => (
                              <li
                                key={t}
                                className="flex gap-2.5 text-[13px] leading-7 text-muted"
                              >
                                <span className="mt-1 grid size-5 shrink-0 place-items-center rounded-full bg-accent-soft text-[11px] font-semibold text-fg">
                                  {(n + 1).toLocaleString("fa-IR")}
                                </span>
                                <span>{t}</span>
                              </li>
                            ))}
                          </ol>
                        )}
                        {b.items && (
                          <ul className="space-y-1.5">
                            {b.items.map((t) => (
                              <li
                                key={t}
                                className="flex gap-2 text-[13px] leading-7 text-muted"
                              >
                                <span className="mt-3 size-1.5 shrink-0 rounded-full bg-accent" />
                                <span>{t}</span>
                              </li>
                            ))}
                          </ul>
                        )}
                        {b.tip && (
                          <p className="rounded-lg border border-accent/30 bg-accent-soft px-3 py-2 text-[12px] leading-6 text-fg">
                            💡 {b.tip}
                          </p>
                        )}
                      </div>
                    ))}
                  </div>
                </section>
              ))}
            </div>
          </div>
        </DialogContent>
      </Dialog>
    </>
  );
}
